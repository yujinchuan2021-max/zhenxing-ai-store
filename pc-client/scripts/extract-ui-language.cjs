const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.resolve(__dirname, "..");
const appPath = path.join(root, "src", "App.tsx");
const generatedPath = path.join(root, "src", "language", "generated.ts");
const sourceText = fs.readFileSync(appPath, "utf8");
const sourceFile = ts.createSourceFile(
  appPath,
  sourceText,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TSX
);
const entries = new Map();
const replacements = [];
const dataDeclarations = new Set([
  "browserEnvironmentFallback",
  "builtInBanners",
  "builtInBrand",
  "ENVIRONMENT_NAMES",
  "groups"
]);

if (fs.existsSync(generatedPath)) {
  const generatedSource = fs.readFileSync(generatedPath, "utf8");
  const rowPattern = /^\s*("auto\.[a-f0-9]+"):\s*("(?:[^"\\]|\\.)*"),$/gm;
  for (const match of generatedSource.matchAll(rowPattern)) {
    entries.set(JSON.parse(match[1]), JSON.parse(match[2]));
  }
}

function hasHan(value) {
  return /\p{Script=Han}/u.test(value);
}

function keyFor(value) {
  const key = `auto.${crypto.createHash("sha256").update(value).digest("hex").slice(0, 12)}`;
  entries.set(key, value);
  return key;
}

function isInsideDataDeclaration(node) {
  let current = node;
  while (current) {
    if (
      ts.isVariableDeclaration(current) &&
      ts.isIdentifier(current.name) &&
      dataDeclarations.has(current.name.text)
    ) {
      return true;
    }
    current = current.parent;
  }
  return false;
}

function isTypeOrLogicLiteral(node) {
  const parent = node.parent;
  if (!parent || isInsideDataDeclaration(node)) return true;
  if (ts.isLiteralTypeNode(parent) || ts.isCaseClause(parent)) return true;
  if (
    (ts.isPropertyAssignment(parent) || ts.isMethodDeclaration(parent)) &&
    parent.name === node
  ) return true;
  if (ts.isElementAccessExpression(parent) && parent.argumentExpression === node) {
    return true;
  }
  if (ts.isBinaryExpression(parent)) {
    const logicalOperators = new Set([
      ts.SyntaxKind.EqualsEqualsToken,
      ts.SyntaxKind.EqualsEqualsEqualsToken,
      ts.SyntaxKind.ExclamationEqualsToken,
      ts.SyntaxKind.ExclamationEqualsEqualsToken
    ]);
    if (logicalOperators.has(parent.operatorToken.kind)) return true;
  }
  let current = node;
  while (current && current.parent) {
    if (ts.isCallExpression(current.parent)) {
      const expression = current.parent.expression;
      if (ts.isIdentifier(expression) && expression.text === "useState") {
        return true;
      }
      break;
    }
    if (
      ts.isStatement(current.parent) ||
      ts.isJsxExpression(current.parent) ||
      ts.isPropertyAssignment(current.parent)
    ) break;
    current = current.parent;
  }
  return false;
}

function quote(value) {
  return JSON.stringify(value);
}

function addReplacement(start, end, value) {
  replacements.push({ start, end, value });
}

function visit(node) {
  if (ts.isTemplateExpression(node) && hasHan(node.getText(sourceFile))) {
    if (!isTypeOrLogicLiteral(node)) {
      let template = node.head.text;
      const variables = [];
      node.templateSpans.forEach((span, index) => {
        const name = `value${index + 1}`;
        template += `{${name}}${span.literal.text}`;
        variables.push(`${name}: ${span.expression.getText(sourceFile)}`);
      });
      const key = keyFor(template);
      addReplacement(
        node.getStart(sourceFile),
        node.end,
        `uiText(${quote(key)}, { ${variables.join(", ")} })`
      );
      return;
    }
  }

  if (
    (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) &&
    hasHan(node.text) &&
    !isTypeOrLogicLiteral(node)
  ) {
    const key = keyFor(node.text);
    const replacement = ts.isJsxAttribute(node.parent)
      ? `{uiText(${quote(key)})}`
      : `uiText(${quote(key)})`;
    addReplacement(node.getStart(sourceFile), node.end, replacement);
    return;
  }

  if (ts.isJsxText(node) && hasHan(node.text)) {
    const value = node.text.replace(/\s+/g, " ").trim();
    if (value) {
      const key = keyFor(value);
      addReplacement(node.getStart(sourceFile), node.end, `{uiText(${quote(key)})}`);
    }
    return;
  }

  ts.forEachChild(node, visit);
}

visit(sourceFile);

let rewritten = sourceText;
for (const replacement of replacements.sort((a, b) => b.start - a.start)) {
  rewritten =
    rewritten.slice(0, replacement.start) +
    replacement.value +
    rewritten.slice(replacement.end);
}

const rows = [...entries.entries()].sort(([left], [right]) =>
  left.localeCompare(right)
);
const generated = [
  "// Generated by scripts/extract-ui-language.cjs. Keep product/catalog data elsewhere.",
  "export const generatedChineseMessages = {",
  ...rows.map(([key, value]) => `  ${quote(key)}: ${quote(value)},`),
  "} as const;",
  ""
].join("\n");

fs.writeFileSync(appPath, rewritten, "utf8");
fs.writeFileSync(generatedPath, generated, "utf8");
process.stdout.write(
  `Language catalog now contains ${entries.size} messages; extracted ${replacements.length} new occurrences.\n`
);
